--[[
Purpose: Text of the startup.lua that scripts/setup.lua writes on a node, so the generated file and the repository's own
  startup.lua cannot drift apart (the generated one once lacked the OTA recovery).
Public API: render(opts) -> text      opts: role, id, config (path)
Notes: role, id and config are written with %q, so a quote in an id cannot break the file. startup.lua first undoes a half-done or
  unconfirmed over-the-air update (src/shared/ota_recovery.lua), then starts the role.
]]

local startup_template = {}

local ROLES = { "master", "signal", "sensor", "switch", "train", "station", "depot", "panel" }

local function is_role(role)
  for _, r in ipairs(ROLES) do if r == role then return true end end
  return false
end

function startup_template.render(opts)
  local o = opts or {}
  if not is_role(o.role) then return nil, "unknown role: " .. tostring(o.role) end
  if type(o.id) ~= "string" or not o.id:match("^[%w_%-%.]+$") then return nil, "node id may only contain letters, digits, _ - ." end
  if type(o.config) ~= "string" or o.config == "" then return nil, "config path is missing" end

  local lines = {
    "-- CreateRailNet-V3 auto-generated by setup.lua",
    "-- Role: " .. o.role .. "  ID: " .. o.id,
    '-- To reconfigure: delete this file and run: shell.run("scripts/setup.lua")',
    "",
    "local CRN_ROLE   = " .. string.format("%q", o.role),
    "local CRN_ID     = " .. string.format("%q", o.id),
    "local CRN_CONFIG = " .. string.format("%q", o.config),
    "",
    "local role_entrypoints = {",
    '  master  = "src.master.main",',
    '  signal  = "src.nodes.signal_node",',
    '  sensor  = "src.nodes.sensor_node",',
    '  switch  = "src.nodes.switch_node",',
    '  train   = "src.nodes.train_node",',
    '  station = "src.nodes.station_node",',
    '  depot   = "src.nodes.depot_node",',
    '  panel   = "src.nodes.panel_node",',
    "}",
    "",
    "-- Undo a half-done or unconfirmed over-the-air update before anything else is loaded.",
    'local ok_recovery, recovery = pcall(require, "src.shared.ota_recovery")',
    "if ok_recovery then",
    "  local ran, action, detail = pcall(recovery.recover)",
    '  if ran and action ~= "none" then print("OTA recovery: " .. tostring(action) .. " " .. tostring(detail or "")) end',
    "end",
    "",
    "local entrypoint = role_entrypoints[CRN_ROLE]",
    'if not entrypoint then error("Unknown CRN_ROLE: " .. tostring(CRN_ROLE)) end',
    "",
    "local function read_version()",
    '  if fs and fs.exists and fs.exists("crn_version.txt") then',
    '    local fh = fs.open("crn_version.txt", "r")',
    '    if fh then local v = fh.readLine(); fh.close(); return v end',
    "  end",
    '  return "unknown"',
    "end",
    "",
    'print("CreateRailNet v" .. read_version() .. "  role=" .. CRN_ROLE .. "  id=" .. CRN_ID)',
    "",
    "local mod = require(entrypoint)",
    "if mod and mod.new_runtime then",
    "  mod.new_runtime({ id = CRN_ID, config = CRN_CONFIG }).run()",
    "elseif mod and mod.run then",
    "  mod.run({ id = CRN_ID, config = CRN_CONFIG })",
    "else",
    '  shell.run("run", entrypoint, "--id", CRN_ID, "--config", CRN_CONFIG)',
    "end",
  }
  return table.concat(lines, "\n") .. "\n"
end

startup_template.ROLES = ROLES

return startup_template
