local storelib = require("core.store")
local netz = require("domain.netz")

local P = "/crn_data/netz.lua"

local function setup(opts)
  local fs = cc.fs(opts)
  fs.makeDir("/crn_data")
  local store = storelib.new(fs)
  return netz.new({ store = store, path = P }), fs, store
end

local function names(list, field)
  local out = {}
  for _, x in ipairs(list) do out[#out + 1] = x[field or "name"] end
  return table.concat(out, ",")
end

local function directions(tracks)
  local out = {}
  for _, x in ipairs(tracks) do out[#out + 1] = x.direction end
  return table.concat(out, ",")
end

