Purpose: Netzverzeichnis (src/domain/netz.lua): Bereiche mit Vorlagen, Gleise mit Richtungsbezug, dauerhafte Kennungen ohne Wiederverwendung, wiederholbare Node-Anforderung, Schutz benutzter Objekte, Speichern und Laden, Fehler beim Speichern.
