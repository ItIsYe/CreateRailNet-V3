--[[
Purpose: Was bei der Einrichtung angelegt wurde, laesst sich auch aendern: ein Bahnhof mit mehreren Gleisen laesst sich umbenennen und umbauen (kein zweiter Eintrag, keine Meldung "gehoert schon zum Bahnhof ..." fuer die eigenen Gleise; die Halte der Vorlagen folgen), eine Linie behaelt beim Aendern ihre Kennung, eine Vorlage laesst sich aendern (nicht unter einem laufenden Auftrag) und die Anmeldungen eines umbenannten Bahnhofs tragen den neuen Namen.
]]

local t = dofile("tests/lib/t.lua")
local H = dofile("tests/lib/harness.lua")
local cc = dofile("tests/fakes/cc.lua")
local storelib = require("core.store")
local stationslib = require("domain.stations")
local orderslib = require("domain.orders")
local netz = require("domain.netz")

local function build()
  local h = H.new()
  local z = h.add_node({ id = "hauptstelle", roles = { "zentrale" }, tracks = {} })
  local w = h.add_node({
    id = "weizenhof", roles = { "bahnhof", "anmeldung" }, central = "hauptstelle", registration = "Gleis 1",
    tracks = { { name = "Gleis 1", station_name = "Weizenhof", known = { Zentrallager = 100, Weizenhof = 0 } } },
  })
  local l = h.add_node({
    id = "lager", roles = { "bahnhof" }, central = "hauptstelle",
    tracks = { { name = "Gleis 1", station_name = "Zentrallager", known = { Weizenhof = 100, Zentrallager = 0 } } },
  })
  local sim = h.sim({ { node = "weizenhof", name = "Weizenhof" }, { node = "lager", name = "Zentrallager" } }, 12)
  return h, z, w, l, sim
end

local function ready(h, z, w, sim)
  sim.add_train("Unnamed Train", "Weizenhof", nil, 0)
  h.step(20)
  w.node.roles.anmeldung.submit_registration({ id = "GZ-001", create_name = "GZ-001", display_name = "W", usage = "fracht", mode = "bedarf", length = 4 })
  t.ok(h.until_true(function() local tr = z.node.roles.zentrale.register.get("GZ-001") return tr and tr.state == "gesteuert" end, 60))
  h.step(8)
  return z.node.roles.zentrale
end

local function plain_stations()
  local fs = cc.fs()
  fs.makeDir("/crn_data")
  return stationslib.new({ store = storelib.new(fs), path = "/crn_data/bahnhoefe.lua" })
end

return {
  { "Bahnhof mit mehreren Gleisen aendern: umbenennen und Gleise tauschen, ohne zweiten Eintrag; fremde Gleise und doppelte Namen werden abgelehnt", function()
    local s = plain_stations()
    t.eq(s.set("Hauptbahnhof", { "HBF 1", "HBF 2" }), true)
    t.eq(s.set("Nord", { "Nord 1" }), true)
    t.eq(s.update("Hauptbahnhof", "Zentral", { "HBF 1", "HBF 2", "HBF 3" }), true, "umbenennen und ein Gleis dazu")
    t.eq(s.get("Hauptbahnhof"), nil, "der alte Name ist weg")
    t.eq(#s.get("Zentral").members, 3)
    t.eq(#s.list(), 2, "kein zweiter Eintrag")
    local ok, why = s.update("Zentral", "Nord", { "HBF 1" })
    t.eq(ok, nil); t.contains(why, "gibt es schon")
    ok, why = s.update("Zentral", "Zentral", { "HBF 1", "Nord 1" })
    t.eq(ok, nil); t.contains(why, "gehoert schon zum Bahnhof Nord")
    ok, why = s.update("Gibtsnicht", "X", { "A" })
    t.eq(ok, nil); t.contains(why, "gibt es nicht")
    t.eq(#s.get("Zentral").members, 3, "abgelehnte Aenderungen aendern nichts")
    t.eq(s.update("Zentral", "Zentral", { "HBF 2" }), true, "nur die Gleise aendern")
    t.eq(s.get("Zentral").members[1], "HBF 2")
  end },

